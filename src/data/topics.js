export const getTopicById = (id) =>
  TOPICS.flatMap((cat) => cat.children).find((t) => t.id === id);

export const getCasesByTopic = (topicId) => {
  const topic = getTopicById(topicId);
  return topic ? topic.cases : [];
};

export const getTopicsByCategory = (categoryId) => {
  const cat = TOPICS.find((c) => c.id === categoryId);
  return cat ? cat.children : [];
};

export const getTopicsForCase = (caseId) => {
  return TOPICS.flatMap((cat) =>
    cat.children
      .filter((t) => t.cases.includes(caseId))
      .map((t) => ({ ...t, categoryName: cat.name, categoryIcon: cat.icon }))
  );
};
