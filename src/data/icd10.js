/**
 * Вспомогательная функция стемминга русских медицинских терминов.
 * Удаляет падежные окончания и суффиксы для нахождения однокоренных слов.
 */
function stemTerm(word) {
  if (!word || word.length < 3) return word.toLowerCase();
  return word
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/(иями|ями|ами|ого|его|ому|ему|ыми|ими|ом|ем|ам|ям|ах|ях|ов|ев|ей|ия|ья|ье|ие|ое|ее|ые|ие|ый|ий|ой|ей|ая|яя|ую|юю|ут|ют|ат|ят|ет|ит|ил|ила|или|а|я|у|ю|о|е|ы|и)$/g, "");
}

/**
 * Интеллектуальный поиск диагнозов по коду МКБ-10, названию нозологии и синонимам.
 * Поддерживает стемминг (поиск по корням), префиксный поиск и релевантное ранжирование.
 * 
 * @param {string} query Поисковый запрос врача
 * @param {number} limit Максимальное количество результатов
 * @returns {Array<{code: string, name: string, category: string}>}
 */
export function searchICD10(query, limit = 7) {
  if (!query || query.trim().length === 0) {
    return ICD10_DATABASE.slice(0, limit);
  }

  const qRaw = query.trim().toLowerCase().replace(/ё/g, "е");
  const qTokens = qRaw.split(/[^a-zA-Zа-яА-Я0-9]/).filter(t => t.length > 0);
  const qStems = qTokens.map(stemTerm).filter(t => t.length > 0);

  const scored = [];

  for (const item of ICD10_DATABASE) {
    const codeLower = item.code.toLowerCase();
    const nameLower = item.name.toLowerCase().replace(/ё/g, "е");
    const nameTokens = nameLower.split(/[^a-zA-Zа-яА-Я0-9]/).filter(t => t.length > 0);
    const nameStems = nameTokens.map(stemTerm);

    let score = 0;

    // 1. Точное совпадение с кодом МКБ-10 (напр. "B00.4", "I21.0")
    if (codeLower === qRaw || codeLower.replace(/\./g, "") === qRaw) {
      score += 200;
    } else if (codeLower.startsWith(qRaw)) {
      score += 100;
    }

    // 2. Полное совпадение или префиксное совпадение с названием
    if (nameLower === qRaw) {
      score += 150;
    } else if (nameLower.startsWith(qRaw)) {
      score += 80;
    } else if (nameLower.includes(qRaw)) {
      score += 50;
    }

    // 3. Совпадение по корням слов (стемминг)
    let tokenMatches = 0;
    for (const qs of qStems) {
      if (nameStems.some(ns => ns.startsWith(qs) || qs.startsWith(ns))) {
        tokenMatches++;
      }
    }
    if (qStems.length > 0 && tokenMatches === qStems.length) {
      score += 60; // Все слова запроса найдены в названии
    } else if (tokenMatches > 0) {
      score += tokenMatches * 15;
    }

    // 4. Проверка по синонимам и альтернативным формулировкам
    if (item.synonyms && item.synonyms.length > 0) {
      for (const syn of item.synonyms) {
        const sLower = syn.toLowerCase().replace(/ё/g, "е");
        if (sLower === qRaw) {
          score += 90;
          break;
        } else if (sLower.includes(qRaw)) {
          score += 35;
          break;
        }
        const sStems = sLower.split(/[^a-zA-Zа-яА-Я0-9]/).map(stemTerm).filter(t => t.length > 0);
        if (qStems.some(qs => sStems.some(ss => ss.startsWith(qs) || qs.startsWith(ss)))) {
          score += 20;
          break;
        }
      }
    }

    if (score > 0) {
      scored.push({ item, score });
    }
  }

  // Сортируем по убыванию релевантности
  scored.sort((a, b) => b.score - a.score);

  return scored.slice(0, limit).map(s => s.item);
}
